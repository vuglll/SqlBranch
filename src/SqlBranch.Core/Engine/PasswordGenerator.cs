using System.Security.Cryptography;

namespace SqlBranch.Core.Engine;

/// <summary>Random passwords that meet SQL Server's policy and need no quoting anywhere.</summary>
public static class PasswordGenerator
{
    public const int Length = 32;

    private const string Upper = "ABCDEFGHJKLMNPQRSTUVWXYZ";
    private const string Lower = "abcdefghijkmnopqrstuvwxyz";
    private const string Digits = "23456789";
    private const string All = Upper + Lower + Digits;

    /// <summary>A 32-character password with at least one uppercase letter, one lowercase letter and one digit.</summary>
    public static string Generate()
    {
        var chars = new char[Length];
        chars[0] = Pick(Upper);
        chars[1] = Pick(Lower);
        chars[2] = Pick(Digits);
        for (var i = 3; i < Length; i++)
        {
            chars[i] = Pick(All);
        }

        RandomNumberGenerator.Shuffle(chars.AsSpan());
        return new string(chars);
    }

    private static char Pick(string alphabet) => alphabet[RandomNumberGenerator.GetInt32(alphabet.Length)];
}
